create extension if not exists unaccent;

create or replace function _normalizar_chave(txt text) returns text as $$
  select trim(
    regexp_replace(
      regexp_replace(lower(unaccent(coalesce(txt, ''))), '[-–—/()]', ' ', 'g'),
      '\s+', ' ', 'g'
    )
  )
$$ language sql immutable;

