-- 1) Atualiza clausulas.categoria/subcategoria (cache) para os novos nomes canônicos
update clausulas c
set categoria = m.categoria,
    subcategoria = m.subcategoria
from _mapa_subcategorias_v2 m
where _normalizar_chave(c.subcategoria) = m.chave
  and (c.categoria <> m.categoria or c.subcategoria <> m.subcategoria);

-- 2) Remapeia clausula_categorias (principal e adicionais), evitando violar o UNIQUE
--    (clausula_id, categoria, subcategoria) em caso de colisão após o remapeamento.
with alvo as (
  select cc.id as cc_id, cc.clausula_id, m.categoria as nova_categoria, m.subcategoria as nova_subcategoria
  from clausula_categorias cc
  join _mapa_subcategorias_v2 m on m.chave = _normalizar_chave(cc.subcategoria)
  where cc.categoria <> m.categoria or cc.subcategoria <> m.subcategoria
),
duplicatas as (
  select a.cc_id
  from alvo a
  where exists (
    select 1 from clausula_categorias other
    where other.clausula_id = a.clausula_id
      and other.categoria = a.nova_categoria
      and other.subcategoria = a.nova_subcategoria
      and other.id <> a.cc_id
  )
)
delete from clausula_categorias where id in (select cc_id from duplicatas);

with alvo as (
  select cc.id as cc_id, m.categoria as nova_categoria, m.subcategoria as nova_subcategoria
  from clausula_categorias cc
  join _mapa_subcategorias_v2 m on m.chave = _normalizar_chave(cc.subcategoria)
  where cc.categoria <> m.categoria or cc.subcategoria <> m.subcategoria
)
update clausula_categorias cc
set categoria = a.nova_categoria, subcategoria = a.nova_subcategoria
from alvo a
where cc.id = a.cc_id;

-- 3) Relatório de cláusulas ainda não reconhecidas pelo mapa (revisão manual)
select c.id, c.numero, c.titulo, c.categoria as categoria_atual, c.subcategoria as subcategoria_atual,
       i.nome as instrumento
from clausulas c
join instrumentos i on i.id = c.instrumento_id
where not exists (
  select 1 from _mapa_subcategorias_v2 m where m.chave = _normalizar_chave(c.subcategoria)
)
order by i.nome, c.numero;
